    private final TransportItemRepo repository;
    private final TransportRepository transportRepository;
    private final UserRepo userRepo;
    private final UserService userService;
    private final CarbonService carbonService;

    public TransportItemService(TransportItemRepo repository, TransportRepository transportRepo, UserRepo userRepo, UserService userService, CarbonService carbonService) {
        this.repository = repository;
        this.transportRepository = transportRepo;
        this.userRepo = userRepo;
        this.userService = userService;
        this.carbonService = carbonService;
    }

    private TransportRowDTO toDTO(TransportItem item){
        UUID transportId = item.getObjectId();
        Transport transport = transportRepository.findById(transportId).orElseThrow(() -> new RuntimeException("Couldn't find tranport with id: "+transportId));
        double distance = item.getDistance();
        double co2Value = carbonService.getCarbonValue(transport,distance);
        return new TransportRowDTO(item.getId(),item.getObjectId(),transport.getName(),item.getDistance(),co2Value);
    }

    public List<TransportRowDTO> getTransportItemList(UUID committeeId) {
        // If the transport items don't exist, we create them first with a distance of 0 and authorId set to the committeeId
        // We never need to create more that those transport items for each committee
        List<TransportItem> transportItems = generateTransportItem(committeeId);
        List<TransportRowDTO> result = new java.util.ArrayList<>(List.of());
        for (TransportItem t : transportItems) {
            result.add(toDTO(t));
        }
        return result;
    }

    private TransportItem createTransportItem(Transport transport, UUID committeeId, double distance){
        return new TransportItem(committeeId,committeeId,transport.getId(),distance);
    }

    private List<TransportItem> generateTransportItem(UUID committeeId){
        // Creates transport items for a specific committee
        // Returns the transport items it created
        List<TransportItem> transportItems = repository.findByCommitteeId(committeeId)
                .orElse(new java.util.ArrayList<>(List.of()));
        if (!transportItems.isEmpty()){
            return transportItems;
        }
        List<TransportItem> result = new java.util.ArrayList<>(List.of());
        List<Transport> transports = transportRepository.findAll();
        int expectedSize = 11;
        if (transports.size() != expectedSize){
            throw new RuntimeException("The list of transport means is not "+expectedSize+" and is equal to: "+transports.size());
        }
        for(Transport t : transports){
            TransportItem item = createTransportItem(t,committeeId,0);
            try {
                TransportItem saved = repository.save(item);
                result.add(saved);
            } catch (DataIntegrityViolationException e) {
                // Another concurrent transaction already created this one.
            }
        }
        return result;

    }

    private TransportItem fetchOrCreateTransportItem(TransportItemDTO dto){
        UUID id = userService.parseId(dto.id());
        if (id == null){ // The dto provided doesn't have id
            return new TransportItem(dto);
        }
        Optional<TransportItem> previousItem = repository.findById(id);
        if (previousItem.isEmpty()){ // The item doesn't exist in the DB
            return new TransportItem(dto); // We create the new item with a UUID generated by the Java
        }
        else {
            // The item has to be modified, so we create a food item with the same id as the previous one with the data from the dto
            return TransportItem.createTransportItemWithId(dto);
        }
    }

    public List<TransportRowDTO> saveTransportItems(List<TransportItemDTO> items) {
        List<TransportRowDTO> result = new ArrayList<>();
        for (TransportItemDTO dto : items){
            TransportItem item = fetchOrCreateTransportItem(dto);

            System.out.println("The item that should be saved is:");
            System.out.println(item.getObjectId()+" - "+dto.distance());
            TransportItem savedItem = repository.save(item);

            result.add(createTransportItemDTO(savedItem));
        }
        return result;
    }

    private TransportRowDTO createTransportItemDTO(TransportItem item) {
        Transport transport = transportRepository.findById(item.getObjectId()).orElseThrow(() -> new RuntimeException("Couldn't find transport with id: "+item.getObjectId()));
        double co2Value = carbonService.getCarbonValue(transport,item.getDistance());
        return new TransportRowDTO(item.getId(),transport.getId(),transport.getName(),item.getDistance(),co2Value);
    }

