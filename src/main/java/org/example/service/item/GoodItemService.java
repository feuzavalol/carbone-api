package org.example.service.item;

import jakarta.persistence.EntityNotFoundException;
import org.example.model.*;
import org.example.model.item.GoodItem;
import org.example.model.item.GoodItemDTO;
import org.example.model.requests.GoodItemRequest;
import org.example.model.responses.GoodRowDTO;
import org.example.repository.*;
import org.example.repository.item.GoodItemRepo;
import org.example.service.CarbonService;
import org.example.service.GoodService;
import org.example.service.UserService;
import org.springframework.stereotype.Service;
import org.springframework.transaction.annotation.Transactional;

import java.util.ArrayList;
import java.util.List;
import java.util.Optional;
import java.util.UUID;

@Service
public class GoodItemService {

    private final GoodItemRepo repository;
    private final GoodService goodService;
    private final UserRepo userRepo;
    private final UserService userService;
    private final CommitteeRepo committeeRepo;
    private final CarbonService carbonService;

    // Spring injects the repositories automatically via the constructor
    public GoodItemService(GoodItemRepo goodItemRepo, GoodService goodService, UserRepo userRepo, UserService userService, CommitteeRepo committeeRepo, CarbonService carbonService) {
        this.repository = goodItemRepo;
        this.goodService = goodService;
        this.userRepo = userRepo;
        this.userService = userService;
        this.committeeRepo = committeeRepo;
        this.carbonService = carbonService;
    }

    private boolean checkGoodRequest(GoodItem request){
        return goodService.existsById(request.getObjectId()) && userRepo.existsById(request.getAuthorId()) && committeeRepo.existsById(request.getCommitteeId());
    }

    @Transactional
    public void createAndSaveGoodItem(GoodItem goodItem) {
        repository.save(goodItem);
    }

    public GoodRowDTO createGoodRowDTO(GoodItem item){
        Good good = goodService.getGood(item.getObjectId());
        double co2Value = carbonService.getCarbonValue(good,item.getQuantity());
        return new GoodRowDTO(item.getId(),good.getId(),good.getName(),item.getQuantity(),good.getExpectedUnit(),co2Value);
    }

    public List<GoodRowDTO> saveGoodItems(List<GoodItemDTO> goodItemDTOS){
        List<GoodRowDTO> result = new ArrayList<>();
        for (GoodItemDTO dto : goodItemDTOS){
            UUID id = userService.parseId(dto.id());
            GoodItem item;
            if (id != null){ //
                Optional<GoodItem> previousItem = repository.findById(id);
                if (previousItem.isEmpty()){ // The item doesn't exist in the DB
                    item = new GoodItem(dto); // We create the new item with a UUID generated by the Java
                }
                else {
                    // The item has to be modified, so we create a good item with the same id as the previous one with the data from the dto
                    item = GoodItem.createGoodItemWithId(dto);
                }
            }
            else { // The item provided doesn't have id
                item = new GoodItem(dto);
            }
            System.out.println("The item that should be saved is:");
            System.out.println(item.getObjectId());
            GoodItem savedItem = repository.save(item);

            result.add(createGoodRowDTO(savedItem));
        }
        return result;
    }

    public GoodItemDTO removeGoodItem(GoodItemDTO dto){
        UUID id = userService.parseId(dto.id());
        if (id != null){
            if (repository.existsById(id)){
                repository.deleteById(id);
                return dto;
            }
            else{
                throw new EntityNotFoundException("The item you wanted to remove doesn't exist");
            }
        }
        else{
            throw new RuntimeException("The id provided is null");
        }
    }

    public List<GoodRowDTO> getGoodItemList(GoodItemRequest request){
        // This function is used by the UI to fetch already saved carbon footprint
        // If there is no element in the database yet, it returns an empty list
        UUID committeeId = request.committeeId();
        // System.out.println(committeeId);
        List<GoodItem> goodItems = repository.findByCommitteeId(committeeId)
                .orElse(new java.util.ArrayList<>(List.of()));
        List<GoodRowDTO> result = new java.util.ArrayList<>(List.of());
        for(GoodItem f : goodItems){
            Good good = goodService.getGood(f.getObjectId());
            double carbonValue = carbonService.getCarbonValue(good,f.getQuantity());
            result.add(new GoodRowDTO(f.getId(),good.getId(),good.getName(),f.getQuantity(),good.getExpectedUnit(),carbonValue));
        }
        // System.out.println(result);
        return result;
    }
}
